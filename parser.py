def normalize_key(key):
    key_clean = key.strip().replace("ё", "е")
    key_lower = key_clean.lower().strip()

    if key_lower in ALIASES:
        return ALIASES[key_lower]

    for field in KNOWN_FIELDS:
        if field.lower().replace("ё", "е") == key_lower:
            return field

    return key.strip()


def parse_partner_message(text):
    data = {}

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue

        line = re.sub(r"^[•\-\*\d\.\)\s]+", "", line).strip()

        if ":" in line:
            key, value = line.split(":", 1)
        elif " - " in line:
            key, value = line.split(" - ", 1)
        else:
            continue

        key = normalize_key(key)
        value = value.strip()

        if key and value:
            data[key] = value

    return data


def is_partner_request(text):
    data = parse_partner_message(text)
    strong_fields = ["Название", "Бренд", "Клиент", "ИНН", "Адрес ресторана", "Контакт"]
    matches = sum(1 for field in strong_fields if field in data)
    return matches >= 2


def format_preview(data):
    if not data:
        return "Не смог распознать поля."

    important_order = [
        "Название", "Бренд", "Клиент", "Контакт", "ИНН", "Адрес ресторана",
        "Локация", "Номер телефона для аккаунта", "ФИО директора",
    ]

    lines = ["📌 Проверьте данные сделки:", ""]
    shown = set()

    for key in important_order:
        if key in data:
            lines.append(f"{key}: {data[key]}")
            shown.add(key)

    other = [(k, v) for k, v in data.items() if k not in shown]
    if other:
        lines.append("")
        lines.append("Дополнительные поля:")
        for key, value in other[:25]:
            lines.append(f"{key}: {value}")

    return "\n".join(lines)
